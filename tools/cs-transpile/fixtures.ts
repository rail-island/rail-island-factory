// The C# transpiler's fixtures (`pnpm cs:pilot --fixtures`): every exported function of
// fixtures/constructs.ts, run in Node and as transpiled C#, the JSON of the two compared
// exactly. A regression check of the transpiler and its runtime, construct by construct,
// independent of any design. Writes only to the gitignored export/cs-fixtures/.
// Node-only; run through main.ts.

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";
import { HERE, ROOT } from "./common.ts";
import { diff } from "./compare.ts";
import { Transpiler } from "./transpile.ts";

const FIXTURES = path.join(HERE, "fixtures");
const OUT = path.join(ROOT, "export", "cs-fixtures");
const RUNTIME = ["JsArray.cs", "JsCollections.cs", "JsRt.cs", "ModelNode.cs"];

type Json = Parameters<typeof diff>[0];

export async function runFixtures(): Promise<boolean> {
  const mod = (await import(pathToFileURL(path.join(FIXTURES, "constructs.ts")).href)) as Record<string, () => unknown>;
  const names = Object.keys(mod).filter((k) => typeof mod[k] === "function").sort();
  const t = new Transpiler(FIXTURES, path.join(HERE, "tsconfig.json"));
  const result = t.transpile([{ source: "constructs.ts", names }], []);
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, "Generated"), { recursive: true });
  fs.mkdirSync(path.join(OUT, "Runtime"), { recursive: true });
  for (const [file, code] of result.files) fs.writeFileSync(path.join(OUT, "Generated", file), code);
  fs.writeFileSync(path.join(OUT, "Generated", "FixtureTable.g.cs"), `// Generated by tools/cs-transpile/fixtures.ts.\nusing System;\n\nnamespace RailIsland.Factory.Generated;\n\npublic static class FixtureTable\n{\n    public static readonly (string, Func<object>)[] All =\n    {\n${names.map((n) => `        (${JSON.stringify(n)}, () => Mod_constructs.${n}()),`).join("\n")}\n    };\n}\n`);
  for (const f of RUNTIME) fs.copyFileSync(path.join(HERE, "runtime", f), path.join(OUT, "Runtime", f));
  fs.copyFileSync(path.join(HERE, "tool", "Fixtures.csproj"), path.join(OUT, "Fixtures.csproj"));
  fs.copyFileSync(path.join(HERE, "tool", "FixturesProgram.cs"), path.join(OUT, "FixturesProgram.cs"));
  const env = { ...process.env, DOTNET_CLI_TELEMETRY_OPTOUT: "1", DOTNET_NOLOGO: "1" };
  execFileSync("dotnet", ["build", "-c", "Release", "-v", "q", "-nologo"], { cwd: OUT, env, stdio: ["ignore", "pipe", "pipe"] });
  const lines = execFileSync("dotnet", [path.join("bin", "Release", "net8.0", "Fixtures.dll")], { cwd: OUT, env, encoding: "utf8" }).trim().split("\n");
  const cs = new Map(lines.map((l) => [l.slice(0, l.indexOf("\t")), JSON.parse(l.slice(l.indexOf("\t") + 1)) as Json]));
  let failed = 0;
  for (const n of names) {
    const js = JSON.parse(JSON.stringify(mod[n]!())) as Json;
    const d = diff(js, cs.get(n) ?? null);
    if (d) failed++;
    console.log(`  ${d ? "DIFF" : "same"}  ${n}${d ? `: ${d}` : ""}`);
  }
  console.log(`fixtures: ${names.length - failed} of ${names.length} identical`);
  return failed === 0;
}
