// The road and rail vehicles' link-preview cards (renderCard.ts, docs/site/seo-pages.md
// "Link previews"): rendered by `pnpm build:models` for every confirmed vehicle whose
// thumbnail is a side view, kept as JPEG in build-cache/cards/ under its design's key
// and CARD_VERSION (so a build renders only the cards whose model changed), and copied
// into the export's cards/ folder, which the site's build serves at /cards/<id>.jpg.
// Only a whole export has them; nothing of the game reads them.
//
//   build-cache/cards/<id>.jpg     a card, 1200 x 630
//   build-cache/cards/index.json   the key each card was rendered for

import fs from "node:fs";
import path from "node:path";
import { PNG } from "pngjs";
import sharp from "sharp";
import { CARD_VERSION, renderGlbCard } from "./renderCard.ts";

/** The cards' folder, in the build cache and in the export. */
export const CARDS_DIR = "cards";
const INDEX_FILE = "index.json";
const NOTE = "Generated by pnpm build:models (docs/site/seo-pages.md); commit it with build-cache/. Never edit by hand.";
/** The JPEG quality: a card is about 30 KB. */
const QUALITY = 80;

/** The key a card is rendered for: its design's build-cache key and the card's version. */
export function cardKey(designKey: string): string {
  return `${CARD_VERSION}:${designKey}`;
}

/** The stored cards' keys, by id (empty for none, or an unreadable index). */
export function readCardKeys(cacheDir: string): Record<string, string> {
  try {
    const stored = JSON.parse(fs.readFileSync(path.join(cacheDir, CARDS_DIR, INDEX_FILE), "utf8")) as { keys?: Record<string, string> };
    return stored.keys ?? {};
  } catch {
    return {};
  }
}

/**
 * Renders the cards `wanted` lists whose stored key differs (an unkeyed design's
 * every time), removes every other card, and copies them all into `dir`/cards.
 * `glbOf` builds a design's default GLB. Returns the ids with a card.
 */
export async function generateCards(
  dir: string,
  cacheDir: string,
  wanted: ReadonlyArray<{ id: string; key: string | null }>,
  glbOf: (id: string) => Uint8Array,
): Promise<Set<string>> {
  const cacheCards = path.join(cacheDir, CARDS_DIR);
  const outCards = path.join(dir, CARDS_DIR);
  fs.mkdirSync(cacheCards, { recursive: true });
  fs.mkdirSync(outCards, { recursive: true });
  const stored = readCardKeys(cacheDir);
  const keys: Record<string, string> = {};
  for (const { id, key } of [...wanted].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))) {
    const file = path.join(cacheCards, `${id}.jpg`);
    const k = key === null ? null : cardKey(key);
    if (k === null || stored[id] !== k || !fs.existsSync(file)) {
      const png = PNG.sync.write(renderGlbCard(glbOf(id)));
      fs.writeFileSync(file, await sharp(png).jpeg({ quality: QUALITY, mozjpeg: true }).toBuffer());
    }
    if (k !== null) keys[id] = k;
    const out = path.join(outCards, `${id}.jpg`);
    const bytes = fs.readFileSync(file);
    if (!fs.existsSync(out) || !bytes.equals(fs.readFileSync(out))) fs.writeFileSync(out, bytes);
  }
  const ids = new Set(wanted.map((w) => w.id));
  for (const folder of [cacheCards, outCards]) {
    for (const name of fs.readdirSync(folder)) if (name.endsWith(".jpg") && !ids.has(name.slice(0, -4))) fs.rmSync(path.join(folder, name));
  }
  const text = `${JSON.stringify({ note: NOTE, version: CARD_VERSION, keys }, null, 1)}\n`;
  const index = path.join(cacheCards, INDEX_FILE);
  if (!fs.existsSync(index) || fs.readFileSync(index, "utf8") !== text) fs.writeFileSync(index, text);
  return ids;
}
