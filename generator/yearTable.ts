// The year each vehicle type entered service (docs/models/openttd-figures.md,
// "Years"): a real-world fact, kept apart from any one consumer of it. The model
// page shows it, and the OpenTTD export takes it as the vehicle's introduction
// date (src/openttd/properties.ts). A variant that entered service in another year
// (a later livery, a sister class) states its own. "approx" marks a year that is
// an estimate: an unclear first-service year.
//
// Keyed by the exported model id without its `proc-vehicle-` prefix, and kept apart
// from the designs on purpose, like countryTable.ts: a design module is bundled
// into each of its models' JS files, so a field stated there would rewrite every
// model of that module. Read by the catalog (catalog.ts) and the build's checks;
// not part of the game's meta.

import type { ParamValues } from "./design.ts";

/** A model's year in service: the default build's, and each variant's that differs. */
export interface ModelYear {
  year: number;
  /** Set when the year is an estimate. */
  approx?: true;
  /** The variants that entered service in another year. */
  variants?: Array<{ params: ParamValues; year: number }>;
}

type VariantYear = { params: ParamValues; year: number };

const at = (params: ParamValues, year: number): VariantYear => ({ params, year });
const year = (y: number, ...variants: VariantYear[]): ModelYear => ({ year: y, ...(variants.length ? { variants } : {}) });
const approx = (y: number, ...variants: VariantYear[]): ModelYear => ({ ...year(y, ...variants), approx: true });

