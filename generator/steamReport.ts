// Writes the measured comparison of every steam transfer (steamComparison.ts) to
// assets/<folder>/COMPARISON-<key>.md. Node only:
//
//   pnpm exec tsx generator/steamReport.ts [key ...]

import fs from "node:fs";
import { execSync } from "node:child_process";
import { STEAM_TRANSFERS, steamComparison, worstPixels } from "./steamComparison.ts";
import { meanAbsoluteError } from "./csdCoachComparison.ts";

const ROOT = new URL("../", import.meta.url);
const f2 = (v: number): string => v.toFixed(2);
const box = (b: number[]): string => b.map((v) => (Math.round(v * 10) / 10).toString()).join(", ");

function revision(): string {
  try {
    return execSync("git rev-parse --short HEAD", { cwd: ROOT, encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

export function steamReport(key: string): string {
  const tr = STEAM_TRANSFERS.find((t) => t.key === key)!;
  const rows = steamComparison(key);
  const [w, h] = rows[0]!.canvas;
  const lines = [
    `# ${tr.title} - native comparison`,
    "",
    `**Covers** - the measured side-view comparison of \`${tr.id}\`${tr.params ? ` (${Object.entries(tr.params).map(([k, v]) => `${k} ${v}`).join(", ")})` : ""} with vlakosimdb \`${key}\`.`,
    "**Code** - `generator/steamComparison.ts`, `generator/steamReport.ts`, `generator/steamLocos.ts`",
    "**See also** - [steam-locomotives.md](../../docs/models/steam-locomotives.md), [SOURCES.md](SOURCES.md)",
    "",
    `Canvas: \`native/${key}/${tr.view}.bmp\`, ${w} x ${h} px at 0.1 m a pixel (${w / 10} x ${h / 10} m), origin top left, x right, y down.`,
    "The model is measured at rest from the orthographic side extents of the named source-tree scopes:",
    `u = 10 * (${f2(tr.centre)} - X), v = 10 * (${h / 10} - y). Percentages: x% = 100 x / W, y% = 100 y / H, w% = 100 w / W, h% = 100 h / H;`,
    "delta = model - source in percentage points. Generated by `pnpm exec tsx generator/steamReport.ts` at model revision " + `\`${revision()}\`.`,
    "",
    "| id | element | source box px | model box px | source x / y / w / h % | model x / y / w / h % | delta pp | worst px | tol px | uncertainty |",
    "|---|---|---|---|---|---|---|---|---:|---|",
  ];
  for (const r of rows) {
    const mb = [r.model[0]!, r.model[1]!, r.model[0]! + r.model[2]!, r.model[1]! + r.model[3]!];
    lines.push(`| ${r.id} | ${r.element} | ${box(r.box)} | ${box(mb)} | ${r.sourcePercent.map(f2).join(" / ")} | ${r.modelPercent.map(f2).join(" / ")} | ${r.delta.map(f2).join(" / ")} | ${f2(worstPixels(r))} | ${r.tolerancePixels} | ${r.uncertainty} |`);
  }
  lines.push("", `Mean absolute error over x, y, w, h of all ${rows.length} boxes: **${meanAbsoluteError(rows).toFixed(3)} pp** (one native pixel is ${f2(100 / w)} pp across, ${f2(100 / h)} pp up).`, "");
  return lines.join("\n");
}

if (process.argv[1] && process.argv[1].endsWith("steamReport.ts")) {
  const keys = process.argv.slice(2);
  for (const tr of STEAM_TRANSFERS) {
    if (keys.length && !keys.includes(tr.key)) continue;
    const out = new URL(`assets/${tr.folder}/COMPARISON-${tr.key}.md`, ROOT);
    fs.writeFileSync(out, steamReport(tr.key));
    console.log(`wrote ${out.pathname}`);
  }
}
