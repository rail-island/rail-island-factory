// The game's half of the export (docs/models/woods.md): every woods type and every
// tree species packed into ONE standalone ES module, export/woods.js, and
// woods.meta.json describing it. Node-only: esbuild.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { WOODS } from "./woods.ts";
import { SPECIES, treeModelOf } from "./trees.ts";
import { MAX_TREES_PER_CELL, TREE_SEEDS, type WoodsParam } from "./woodsApi.ts";
import { leanMeshBuilder, writeIfChanged } from "./jsModel.ts";

const GENERATOR_DIR = path.dirname(fileURLToPath(import.meta.url));

/** The one module the game imports: every woods type and every tree species. */
export const WOODS_FILE = "woods.js";
export const WOODS_META_FILE = "woods.meta.json";
/** What earlier exports wrote instead (one module per woods type, the trees apart); removed on build. */
const STALE = ["woods", "trees.js"];

/** One woods type as woods.meta.json lists it. */
export interface WoodsMetaEntry {
  name: string;
  label: string;
  swatch: { r: number; g: number; b: number };
  floor: { r: number; g: number; b: number };
  /** The type's enum parameters, `density` first (woodsApi.ts WoodsParam). */
  params: WoodsParam[];
}

/** One tree species as woods.meta.json lists it. */
export interface TreeMetaEntry {
  species: string;
  /** The model id of the catalog design that draws the species. */
  id: string;
  /** The parameter values that pick the species on that design (the autumn larch's season). */
  params: Record<string, string>;
}

export interface WoodsMeta {
  note: string;
  /** The hard limit every distribute() keeps (woodsApi.ts). */
  maxTreesPerCell: number;
  /** How many shapes every species has: a TreeSlot's `seed` is 1..treeSeeds (woodsApi.ts). */
  treeSeeds: number;
  /** The module with every woods type and tree species: WOODS_FILE. */
  module: string;
  trees: TreeMetaEntry[];
  woods: WoodsMetaEntry[];
}

/** The woods meta: every species, then every woods type, each sorted by key. */
export function woodsMeta(): WoodsMeta {
  return {
    note: "Generated by rail-island-factory (`pnpm build`). Do not edit -- change generator/woods.ts and rebuild.",
    maxTreesPerCell: MAX_TREES_PER_CELL,
    treeSeeds: TREE_SEEDS,
    module: WOODS_FILE,
    trees: [...SPECIES].sort().map((species) => ({ species, ...treeModelOf(species) })),
    woods: [...WOODS].map((w) => w.design).sort((a, b) => a.name.localeCompare(b.name)).map((d) => ({
      name: d.name,
      label: d.label,
      swatch: { ...d.swatch },
      floor: { ...d.floor },
      params: d.params.map((p) => ({ ...p, values: p.values.map((v) => ({ ...v })) })),
    })),
  };
}

/**
 * Every woods type and every tree species in ONE standalone module, what the game
 * plants its forests with (no imports, no Node APIs):
 *
 *   WOODS                                 every woods type's meta: name, label, swatch, floor, params
 *   woodsType(name)                       { variant(values), distribute(ctx, out), sample(u, v, out) }:
 *                                         variant(values) returns { distribute, sample } for one choice
 *                                         of the type's parameters; the others are the defaults'
 *   MAX_TREES_PER_CELL, MASK_RADIUS       the distribution contract (woodsApi.ts)
 *   TREE_SEEDS                            how many shapes every species has: a slot's
 *                                         `seed` is 1..TREE_SEEDS
 *   SPECIES                               every tree species key
 *   buildTree(THREE, species, detail, values?)
 *                                         a Group named proc-tree-<species> with the meshes `trunk`
 *                                         and `foliage`; detail is "high" | "low" | "coarse" | "max";
 *                                         values picks the species design's parameters: a
 *                                         slot's tree is { seed: String(slot.seed) }
 *
 * The trees are the catalog designs' triangles exactly: the same functions run.
 */
export async function bundleGame(): Promise<string> {
  const result = await build({
    stdin: {
      contents: [
        `import { buildTree as tree, treeOptions, SPECIES as species } from "./trees.ts";`,
        `import { WOODS as all } from "./woods.ts";`,
        `export { MAX_TREES_PER_CELL, MASK_RADIUS, TREE_SEEDS } from "./woodsApi.ts";`,
        `export const SPECIES = [...species];`,
        `export function buildTree(THREE, s, detail = "high", values) {`,
        `  if (!species.includes(s)) throw new Error("unknown tree species " + s);`,
        `  if (detail !== "high" && detail !== "low" && detail !== "coarse" && detail !== "max") throw new Error("unknown tree detail " + detail);`,
        `  const group = tree(s, detail, values ? treeOptions(s, values) : undefined).toGroup(THREE, "proc-tree-" + s);`,
        `  group.userData.lod = detail;`,
        `  return group;`,
        `}`,
        `export const WOODS = all.map(({ design: w }) => ({ name: w.name, label: w.label, swatch: w.swatch, floor: w.floor, params: w.params }));`,
        `export function woodsType(name) {`,
        `  const w = all.find(({ design }) => design.name === name)?.design;`,
        `  if (!w) throw new Error("unknown woods type " + name);`,
        // the planter for one choice of the parameters, resolved once by the caller; the type's own are the defaults'
        `  return { variant: (values) => w.variant(values), distribute: (ctx, out) => w.distribute(ctx, out), sample: (u, v, out) => w.sample(u, v, out) };`,
        `}`,
      ].join("\n"),
      resolveDir: GENERATOR_DIR,
      sourcefile: "woods-bundle.ts",
      loader: "ts",
    },
    bundle: true,
    minify: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    write: false,
    legalComments: "none",
    plugins: [leanMeshBuilder],
    banner: {
      js: "// Rail Island woods and trees, all in one module. Generated by rail-island-factory; do not edit. WOODS lists the woods types; woodsType(name) returns { variant(values), distribute(ctx, out), sample(u, v, out) } (distribute fills out[0..n) and returns n, at most MAX_TREES_PER_CELL; each slot's seed, 1..TREE_SEEDS, picks the tree's shape); buildTree(THREE, species, detail, values?) returns a THREE.Group with the meshes trunk and foliage, detail high, low, coarse or max; SPECIES lists the species (docs/models/woods.md).",
    },
  });
  return result.outputFiles[0]!.text;
}

/** Writes export/woods.js and woods.meta.json; removes what earlier exports wrote instead. */
export async function generateWoods(dir: string): Promise<WoodsMeta> {
  for (const stale of STALE) fs.rmSync(path.join(dir, stale), { recursive: true, force: true });
  writeIfChanged(path.join(dir, WOODS_FILE), await bundleGame());
  const meta = woodsMeta();
  writeIfChanged(path.join(dir, WOODS_META_FILE), `${JSON.stringify(meta, null, 2)}\n`);
  return meta;
}
