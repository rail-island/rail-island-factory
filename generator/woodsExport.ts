// The woods half of the export (docs/models/woods.md): every woods type as one
// standalone ES module, export/woods/<name>.js, and woods.meta.json listing them
// with the tree species they draw from. Node-only: esbuild.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import crypto from "node:crypto";
import { build } from "esbuild";
import { PNG } from "pngjs";
import { buildGrove } from "./woodsGrove.ts";
import { renderGlbThumb } from "./renderGlbThumb.ts";
import { WOODS } from "./woods.ts";
import { SPECIES, treeId } from "./trees.ts";
import { MAX_TREES_PER_CELL } from "./woodsApi.ts";
import { writeIfChanged } from "./jsModel.ts";

const GENERATOR_DIR = path.dirname(fileURLToPath(import.meta.url));

/** The export's folder of woods modules. */
export const WOODS_DIR = "woods";
export const WOODS_META_FILE = "woods.meta.json";

/** One woods type as woods.meta.json lists it. */
export interface WoodsMetaEntry {
  name: string;
  label: string;
  swatch: { r: number; g: number; b: number };
  floor: { r: number; g: number; b: number };
  /** Path within the export: woods/<name>.js. */
  module: string;
}

/** One tree species as woods.meta.json lists it. */
export interface TreeMetaEntry {
  species: string;
  /** The species' model id; its module is js/<id>.js. */
  id: string;
}

export interface WoodsMeta {
  note: string;
  /** The hard limit every distribute() keeps (woodsApi.ts). */
  maxTreesPerCell: number;
  trees: TreeMetaEntry[];
  woods: WoodsMetaEntry[];
}

/** The woods meta: every species, then every woods type, each sorted by key. */
export function woodsMeta(): WoodsMeta {
  return {
    note: "Generated by rail-island-factory (`pnpm build`). Do not edit -- change generator/woods.ts and rebuild.",
    maxTreesPerCell: MAX_TREES_PER_CELL,
    trees: [...SPECIES].sort().map((species) => ({ species, id: treeId(species) })),
    woods: [...WOODS].map((w) => w.design).sort((a, b) => a.name.localeCompare(b.name)).map((d) => ({
      name: d.name,
      label: d.label,
      swatch: { ...d.swatch },
      floor: { ...d.floor },
      module: `${WOODS_DIR}/${d.name}.js`,
    })),
  };
}

/** The standalone module of one woods type: `woods` (its meta), `distribute`, `sample`. */
export async function bundleWoods(source: string, name: string): Promise<string> {
  const result = await build({
    stdin: {
      contents: [
        `import { ${source} as w } from "./woods.ts";`,
        `export { MAX_TREES_PER_CELL, MASK_RADIUS } from "./woodsApi.ts";`,
        `export const woods = { name: w.name, label: w.label, swatch: w.swatch, floor: w.floor };`,
        `export function distribute(ctx, out) { return w.distribute(ctx, out); }`,
        `export function sample(u, v, out) { w.sample(u, v, out); }`,
      ].join("\n"),
      resolveDir: GENERATOR_DIR,
      sourcefile: `${name}.ts`,
      loader: "ts",
    },
    bundle: true,
    minify: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    write: false,
    legalComments: "none",
    banner: {
      js: `// Rail Island woods type ${name}. Generated by rail-island-factory; do not edit. distribute(ctx, out) fills out[0..n) with the trees a cell grows and returns n (at most MAX_TREES_PER_CELL); sample(u, v, out) writes one representative tree (docs/models/woods.md).`,
    },
  });
  return result.outputFiles[0]!.text;
}

/** The grove thumbnails' prefix in thumbs/: woods-<name>.png (never a design id, which starts proc-). */
export const GROVE_THUMB_PREFIX = "woods-";
const GROVE_SIZE = 512;
/** Beside the thumbnails: each grove's model hash, so an unchanged grove is not re-rendered. */
const GROVE_SOURCES_FILE = ".woods.json";

/** `png` cut to its drawn pixels (a margin kept) and fitted, centred, into a `size` square. */
export function cropToContent(png: PNG, size: number, margin = 0.04): PNG {
  let x0 = png.width, y0 = png.height, x1 = -1, y1 = -1;
  for (let y = 0; y < png.height; y++) {
    for (let x = 0; x < png.width; x++) {
      if (png.data[(y * png.width + x) * 4 + 3]! === 0) continue;
      if (x < x0) x0 = x;
      if (x > x1) x1 = x;
      if (y < y0) y0 = y;
      if (y > y1) y1 = y;
    }
  }
  const out = new PNG({ width: size, height: size });
  if (x1 < 0) return out;
  const side = Math.max(x1 - x0 + 1, y1 - y0 + 1) * (1 + 2 * margin);
  const cx = (x0 + x1 + 1) / 2, cy = (y0 + y1 + 1) / 2;
  const k = side / size;
  // box-filter each target pixel over the source pixels it covers
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const sx0 = cx - side / 2 + x * k, sy0 = cy - side / 2 + y * k;
      let r = 0, g = 0, b = 0, a = 0, n = 0;
      for (let sy = Math.floor(sy0); sy < Math.ceil(sy0 + k); sy++) {
        for (let sx = Math.floor(sx0); sx < Math.ceil(sx0 + k); sx++) {
          n++;
          if (sx < 0 || sy < 0 || sx >= png.width || sy >= png.height) continue;
          const o = (sy * png.width + sx) * 4;
          const al = png.data[o + 3]!;
          r += png.data[o]! * al; g += png.data[o + 1]! * al; b += png.data[o + 2]! * al; a += al;
        }
      }
      const o = (y * size + x) * 4;
      if (a > 0) {
        out.data[o] = Math.round(r / a);
        out.data[o + 1] = Math.round(g / a);
        out.data[o + 2] = Math.round(b / a);
      }
      out.data[o + 3] = n ? Math.round(a / n) : 0;
    }
  }
  return out;
}

/** A woods type's grove thumbnail: the grove at high detail, three-quarter view, cropped to it. */
export function renderGroveThumb(glb: Uint8Array, size = GROVE_SIZE): PNG {
  return cropToContent(renderGlbThumb(glb, size * 2), size);
}

/** Writes export/woods/<name>.js for every woods type and woods.meta.json; removes stale modules. */
export async function generateWoods(dir: string): Promise<WoodsMeta> {
  const woodsDir = path.join(dir, WOODS_DIR);
  fs.mkdirSync(woodsDir, { recursive: true });
  const keep = new Set<string>();
  for (const { design, source } of WOODS) {
    writeIfChanged(path.join(woodsDir, `${design.name}.js`), await bundleWoods(source, design.name));
    keep.add(`${design.name}.js`);
  }
  for (const f of fs.readdirSync(woodsDir)) if (!keep.has(f)) fs.rmSync(path.join(woodsDir, f));
  // the grove thumbnails, re-rendered only when a grove's model changed
  const thumbDir = path.join(dir, "thumbs");
  fs.mkdirSync(thumbDir, { recursive: true });
  const sourcesFile = path.join(thumbDir, GROVE_SOURCES_FILE);
  const previous: Record<string, string> = fs.existsSync(sourcesFile) ? JSON.parse(fs.readFileSync(sourcesFile, "utf8")) : {};
  const sources: Record<string, string> = {};
  for (const { design } of WOODS) {
    const glb = buildGrove(design).toGlb(`Rail Island woods grove (${design.name})`);
    const hash = crypto.createHash("sha256").update(glb).digest("hex");
    sources[design.name] = hash;
    const file = path.join(thumbDir, `${GROVE_THUMB_PREFIX}${design.name}.png`);
    if (previous[design.name] !== hash || !fs.existsSync(file)) fs.writeFileSync(file, PNG.sync.write(renderGroveThumb(glb)));
  }
  for (const f of fs.readdirSync(thumbDir)) {
    if (f.startsWith(GROVE_THUMB_PREFIX) && f.endsWith(".png") && !(f.slice(GROVE_THUMB_PREFIX.length, -4) in sources)) fs.rmSync(path.join(thumbDir, f));
  }
  writeIfChanged(sourcesFile, `${JSON.stringify(Object.fromEntries(Object.entries(sources).sort(([a], [b]) => a.localeCompare(b))), null, 2)}\n`);
  const meta = woodsMeta();
  writeIfChanged(path.join(dir, WOODS_META_FILE), `${JSON.stringify(meta, null, 2)}\n`);
  return meta;
}
