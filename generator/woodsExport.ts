// The woods half of the export (docs/models/woods.md): every woods type as one
// standalone ES module, export/woods/<name>.js, and woods.meta.json listing them
// with the tree species they draw from. Node-only: esbuild.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { WOODS } from "./woods.ts";
import { SPECIES, treeModelOf } from "./trees.ts";
import { MAX_TREES_PER_CELL, type WoodsParam } from "./woodsApi.ts";
import { leanMeshBuilder, writeIfChanged } from "./jsModel.ts";

const GENERATOR_DIR = path.dirname(fileURLToPath(import.meta.url));

/** The export's folder of woods modules. */
export const WOODS_DIR = "woods";
/** Every tree species in one module (bundleTrees), what the game draws its forests with. */
export const TREES_FILE = "trees.js";
export const WOODS_META_FILE = "woods.meta.json";

/** One woods type as woods.meta.json lists it. */
export interface WoodsMetaEntry {
  name: string;
  label: string;
  swatch: { r: number; g: number; b: number };
  floor: { r: number; g: number; b: number };
  /** The type's enum parameters, `density` first (woodsApi.ts WoodsParam). */
  params: WoodsParam[];
  /** Path within the export: woods/<name>.js. */
  module: string;
}

/** One tree species as woods.meta.json lists it. */
export interface TreeMetaEntry {
  species: string;
  /** The model id of the design that draws the species; its module is js/<id>.js. */
  id: string;
  /** The parameter values that pick the species on that design (the autumn larch's season). */
  params: Record<string, string>;
}

export interface WoodsMeta {
  note: string;
  /** The hard limit every distribute() keeps (woodsApi.ts). */
  maxTreesPerCell: number;
  /** Every species in one module: TREES_FILE, buildTree(THREE, species, detail). */
  treesModule: string;
  trees: TreeMetaEntry[];
  woods: WoodsMetaEntry[];
}

/** The woods meta: every species, then every woods type, each sorted by key. */
export function woodsMeta(): WoodsMeta {
  return {
    note: "Generated by rail-island-factory (`pnpm build`). Do not edit -- change generator/woods.ts and rebuild.",
    maxTreesPerCell: MAX_TREES_PER_CELL,
    treesModule: TREES_FILE,
    trees: [...SPECIES].sort().map((species) => ({ species, ...treeModelOf(species) })),
    woods: [...WOODS].map((w) => w.design).sort((a, b) => a.name.localeCompare(b.name)).map((d) => ({
      name: d.name,
      label: d.label,
      swatch: { ...d.swatch },
      floor: { ...d.floor },
      params: d.params.map((p) => ({ ...p, values: p.values.map((v) => ({ ...v })) })),
      module: `${WOODS_DIR}/${d.name}.js`,
    })),
  };
}

/** The standalone module of one woods type: `woods` (its meta), `distribute`, `sample`. */
export async function bundleWoods(source: string, name: string): Promise<string> {
  const result = await build({
    stdin: {
      contents: [
        `import { ${source} as w } from "./woods.ts";`,
        `export { MAX_TREES_PER_CELL, MASK_RADIUS } from "./woodsApi.ts";`,
        `export const woods = { name: w.name, label: w.label, swatch: w.swatch, floor: w.floor };`,
        `export const params = w.params;`,
        // the planter for one choice of the parameters, resolved once by the caller
        `export function variant(values) { return w.variant(values); }`,
        // the defaults', for a caller that has no parameters to pass
        `export function distribute(ctx, out) { return w.distribute(ctx, out); }`,
        `export function sample(u, v, out) { w.sample(u, v, out); }`,
      ].join("\n"),
      resolveDir: GENERATOR_DIR,
      sourcefile: `${name}.ts`,
      loader: "ts",
    },
    bundle: true,
    minify: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    write: false,
    legalComments: "none",
    banner: {
      js: `// Rail Island woods type ${name}. Generated by rail-island-factory; do not edit. variant(values) returns { distribute, sample } for one choice of the type's enum parameters (params; density first): distribute(ctx, out) fills out[0..n) with the trees a cell grows and returns n (at most MAX_TREES_PER_CELL); sample(u, v, out) writes one representative tree. The module's own distribute and sample are the defaults' (docs/models/woods.md).`,
    },
  });
  return result.outputFiles[0]!.text;
}

/**
 * Every tree species in ONE standalone module, `trees.js`: the tree code once
 * instead of fourteen times. The per-species js/proc-tree-<species>.js files stay
 * (the catalog and the site build each tree from its own), but they each carry
 * the whole of trees.ts, since buildTree picks the species at run time -- so the
 * game, which needs every species, imports this one:
 *
 *   buildTree(THREE, species, detail)  a Group named proc-tree-<species> with the
 *                                      meshes `trunk` and `foliage`; detail is
 *                                      "high" | "low" | "coarse"
 *   SPECIES                            every species key
 *
 * The triangles are the per-species modules' exactly: the same functions run.
 */
export async function bundleTrees(): Promise<string> {
  const result = await build({
    stdin: {
      contents: [
        `import { buildTree as tree, SPECIES as species } from "./trees.ts";`,
        `export const SPECIES = [...species];`,
        `export function buildTree(THREE, s, detail = "high") {`,
        `  if (!species.includes(s)) throw new Error("unknown tree species " + s);`,
        `  if (detail !== "high" && detail !== "low" && detail !== "coarse") throw new Error("unknown tree detail " + detail);`,
        `  const group = tree(s, detail).toGroup(THREE, "proc-tree-" + s);`,
        `  group.userData.lod = detail;`,
        `  return group;`,
        `}`,
      ].join("\n"),
      resolveDir: GENERATOR_DIR,
      sourcefile: "trees-bundle.ts",
      loader: "ts",
    },
    bundle: true,
    minify: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    write: false,
    legalComments: "none",
    plugins: [leanMeshBuilder],
    banner: {
      js: "// Rail Island tree species, all in one module. Generated by rail-island-factory; do not edit. buildTree(THREE, species, detail) returns a THREE.Group with the meshes trunk and foliage; detail is high, low or coarse; SPECIES lists the species (docs/models/trees.md).",
    },
  });
  return result.outputFiles[0]!.text;
}

/** Writes export/woods/<name>.js for every woods type and woods.meta.json; removes stale modules. */
export async function generateWoods(dir: string): Promise<WoodsMeta> {
  const woodsDir = path.join(dir, WOODS_DIR);
  fs.mkdirSync(woodsDir, { recursive: true });
  const keep = new Set<string>();
  for (const { design, source } of WOODS) {
    writeIfChanged(path.join(woodsDir, `${design.name}.js`), await bundleWoods(source, design.name));
    keep.add(`${design.name}.js`);
  }
  for (const f of fs.readdirSync(woodsDir)) if (!keep.has(f)) fs.rmSync(path.join(woodsDir, f));
  writeIfChanged(path.join(dir, TREES_FILE), await bundleTrees());
  const meta = woodsMeta();
  writeIfChanged(path.join(dir, WOODS_META_FILE), `${JSON.stringify(meta, null, 2)}\n`);
  return meta;
}
