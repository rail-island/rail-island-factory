// The game's half of the set registry (docs/models/sets.md): one
// export/sets/<set>.meta.json per set, and -- for a set whose definitions have
// landed in the factory -- export/sets/<set>.js, the standalone module the game
// draws the set's types with (bundled from generator/sets/<set>.ts). Node-only.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import ts from "typescript";
import { SETS, type SetDef } from "./registry.ts";
import { writeIfChanged } from "../jsModel.ts";
import { setPins } from "./pinCases.ts";

const SETS_DIR_NAME = "sets";
/** export/sets/pins.json: every landed set's case hashes (pinCases.ts). */
export const PINS_FILE = "pins.json";
const HERE = path.dirname(fileURLToPath(import.meta.url));

/** One set as its meta file lists it: the registry entry without the English text. */
export interface SetMeta {
  note: string;
  set: string;
  collectible?: string;
  landed: boolean;
  defaultId: string;
  retired: Record<string, string>;
  /** In picker order, each with the per-type data the game reads without running the module (a shed's size). */
  types: Array<{ id: string } & Record<string, unknown>>;
  groups?: Array<{ id: string; types: string[] }>;
  /** The set's module beside the meta, once its definitions are the factory's. */
  module?: string;
}

export function setMeta(def: SetDef, extra: Record<string, Record<string, unknown>> = {}): SetMeta {
  return {
    note: "Generated by rail-island-factory (`pnpm build`). Do not edit -- change generator/sets/ and rebuild.",
    set: def.set,
    ...(def.collectible ? { collectible: def.collectible } : {}),
    landed: def.landed,
    defaultId: def.defaultId,
    retired: { ...def.retired },
    types: def.types.map((t) => ({ id: t.id, ...(extra[t.id] ?? {}) })),
    ...(def.groups ? { groups: def.groups.map((g) => ({ id: g.id, types: [...g.types] })) } : {}),
    ...(def.landed ? { module: `${def.set}.js` } : {}),
  };
}

/** The set's source module: generator/sets/<set>.ts. */
export function setSource(def: SetDef): string {
  return path.join(HERE, `${def.set}.ts`);
}

/**
 * A landed set's module, bundled standalone: no imports, no Node APIs, platform
 * neutral, so the game imports it synchronously from core code, the Worker never,
 * Vitest and the headless simulations directly.
 */
export async function bundleSet(def: SetDef): Promise<string> {
  const result = await build({
    entryPoints: [setSource(def)],
    bundle: true,
    minify: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    write: false,
    legalComments: "none",
    banner: { js: `// Rail Island ${def.set} definitions. Generated by rail-island-factory; do not edit (docs/models/sets.md).` },
  });
  return result.outputFiles[0]!.text;
}

/**
 * A landed set's declarations (`<set>.d.ts` beside the module), emitted from its
 * source with TypeScript's isolated-declarations transform: every export of a set
 * module states its type, so the game type-checks its calls into the module.
 */
export function declareSet(def: SetDef): string {
  const file = setSource(def);
  const result = ts.transpileDeclaration(fs.readFileSync(file, "utf8"), {
    fileName: file,
    compilerOptions: { declaration: true, isolatedDeclarations: true, strict: true, target: ts.ScriptTarget.ES2022 },
    reportDiagnostics: true,
  });
  const errors = (result.diagnostics ?? []).map((d) => {
    const line = d.file && d.start !== undefined ? d.file.getLineAndCharacterOfPosition(d.start).line + 1 : 0;
    return `line ${line}: ${ts.flattenDiagnosticMessageText(d.messageText, "\n")}`;
  });
  if (errors.length) throw new Error(`${def.set}: cannot declare its module -- ${errors.join("; ")}`);
  if (/^\s*import\b/m.test(result.outputText)) throw new Error(`${def.set}: a set module must not import (its declarations would)`);
  return `// Rail Island ${def.set} definitions. Generated by rail-island-factory; do not edit (docs/models/sets.md).\n${result.outputText}`;
}

/** Per-type meta data a set module exports as `TYPE_META` (sizes, anchors the game reads without running it). */
async function typeMeta(def: SetDef): Promise<Record<string, Record<string, unknown>>> {
  if (!def.landed) return {};
  // A computed path Vite cannot analyse: `pnpm dev` loads this file through the
  // dev-export plugin (generator/devServer.ts) but never runs the export, so the
  // import is left to Node (test/devExport.test.ts holds every one to this).
  const mod = (await import(/* @vite-ignore */ setSource(def))) as { TYPE_META?: Record<string, Record<string, unknown>> };
  return mod.TYPE_META ?? {};
}

/** Writes export/sets/: every set's meta, and every landed set's module. */
export async function generateSets(dir: string): Promise<SetMeta[]> {
  const outDir = path.join(dir, SETS_DIR_NAME);
  fs.mkdirSync(outDir, { recursive: true });
  const keep = new Set<string>();
  const metas: SetMeta[] = [];
  for (const def of SETS) {
    const meta = setMeta(def, await typeMeta(def));
    metas.push(meta);
    writeIfChanged(path.join(outDir, `${def.set}.meta.json`), `${JSON.stringify(meta, null, 2)}\n`);
    keep.add(`${def.set}.meta.json`);
    if (def.landed) {
      writeIfChanged(path.join(outDir, `${def.set}.js`), await bundleSet(def));
      writeIfChanged(path.join(outDir, `${def.set}.d.ts`), declareSet(def));
      keep.add(`${def.set}.js`);
      keep.add(`${def.set}.d.ts`);
    }
  }
  // the pins of every landed set's cases (pinCases.ts), for the game's import to name redraws
  writeIfChanged(path.join(outDir, PINS_FILE), `${JSON.stringify(setPins(), null, 2)}\n`);
  keep.add(PINS_FILE);
  for (const f of fs.readdirSync(outDir)) if (!keep.has(f)) fs.rmSync(path.join(outDir, f), { recursive: true, force: true });
  return metas;
}
