// bus, a truck, a tram or an aircraft. Keyed by the exported model id (`proc-...`).
// A type built by several works in turn, a generic model and anything uncertain
// names none. The site shows it on the model page and lists each maker with two or
// more models on a page of its own (`/maker/<slug>/`).
//
// Kept apart from the designs on purpose, like countryTable.ts: a design module is
// bundled into each of its models' JS files, so a field stated there would rewrite
// every model of that module. Read by the catalog only (catalog.ts), for the site;
// never by a model, and not part of the game's meta. ASCII names, as the titles.

