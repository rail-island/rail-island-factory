// The game's half of the texture library (docs/models/surfaces.md): every photo set
// copied to export/textures/, and export/surfaces.meta.json - the textures with
// their licence and average colour, and every named surface - for the game to
// import. Node-only.

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SURFACES, TEXTURE_AVERAGE, TEXTURE_CHANNELS, TEXTURE_NAMES, TEXTURE_SLUGS, type SurfacePreset } from "./surfaces.ts";
import { writeIfChanged } from "./jsModel.ts";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
/** The library: assets/textures/. */
export const TEXTURES_DIR = path.join(REPO_ROOT, "assets", "textures");
export const SURFACES_META_FILE = "surfaces.meta.json";
const EXPORT_TEXTURES = "textures";

export interface SurfacesMeta {
  note: string;
  /** Every photo set: its files, licence, source and the sha256 of each file. */
  textures: Array<{ name: string; files: string[]; slug: string; licence: "CC0"; average: string; sha256: Record<string, string> }>;
  surfaces: Record<string, SurfacePreset>;
}

export function surfacesMeta(): SurfacesMeta {
  return {
    note: "Generated by rail-island-factory (`pnpm build`). Do not edit -- change generator/surfaces.ts or assets/textures and rebuild.",
    textures: TEXTURE_NAMES.map((name) => {
      const files = TEXTURE_CHANNELS.map((c) => `${name}_${c}.jpg`);
      return {
        name,
        files,
        slug: TEXTURE_SLUGS[name],
        licence: "CC0" as const,
        average: TEXTURE_AVERAGE[name],
        sha256: Object.fromEntries(files.map((f) => [f, crypto.createHash("sha256").update(fs.readFileSync(path.join(TEXTURES_DIR, f))).digest("hex")])),
      };
    }),
    surfaces: Object.fromEntries(Object.keys(SURFACES).sort().map((id) => [id, { ...SURFACES[id as keyof typeof SURFACES] } as SurfacePreset])),
  };
}

/** Writes export/textures/ (every photo set, nothing else) and export/surfaces.meta.json. */
export function generateSurfaces(dir: string): SurfacesMeta {
  const outDir = path.join(dir, EXPORT_TEXTURES);
  fs.mkdirSync(outDir, { recursive: true });
  const keep = new Set<string>();
  for (const name of TEXTURE_NAMES) {
    for (const c of TEXTURE_CHANNELS) {
      const f = `${name}_${c}.jpg`;
      keep.add(f);
      const bytes = fs.readFileSync(path.join(TEXTURES_DIR, f));
      const out = path.join(outDir, f);
      if (!fs.existsSync(out) || !fs.readFileSync(out).equals(bytes)) fs.writeFileSync(out, bytes);
    }
  }
  for (const f of fs.readdirSync(outDir)) if (!keep.has(f)) fs.rmSync(path.join(outDir, f), { force: true });
  const meta = surfacesMeta();
  writeIfChanged(path.join(dir, SURFACES_META_FILE), `${JSON.stringify(meta, null, 2)}\n`);
  return meta;
}
